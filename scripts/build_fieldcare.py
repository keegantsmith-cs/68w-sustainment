#!/usr/bin/env python3
"""
Build js/fieldcare.js, an OUTLINE of the Prolonged Field Care Field Handbook
(1st Edition, 2025, Breakaway Media, LLC), from docs/field-care/PFC_Handbook_2025_part1.pdf.

    python3 scripts/build_fieldcare.py

The handbook is commercially copyrighted ("All rights reserved"; every page
reads "Do not copy, print, share, or redistribute"). The site shows only
the section and topic outline from its table of contents. No handbook text,
doses or forms, and the PDFs are never committed or hosted.
"""
import json, re, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PDF = ROOT / "docs" / "field-care" / "PFC_Handbook_2025_part1.pdf"
OUT = ROOT / "js" / "fieldcare.js"
BOOK = "Prolonged Field Care Field Handbook, 1st Edition (2025), Breakaway Media, LLC. ISBN 979-8-9902257-4-9"


def toc_lines():
    txt = subprocess.run(["pdftotext", "-layout", "-f", "5", "-l", "7", str(PDF), "-"],
                         capture_output=True, text=True, check=True).stdout
    for line in txt.splitlines():
        s = line.strip()
        if not s or "Copyright" in s or s == "Contents" or "Do not copy" in s or re.fullmatch(r"[ivxlc]+|\d+", s):
            continue
        s = re.sub(r"\s*\.{3,}.*$", "", s).strip()      # drop dot leaders and page numbers
        if s:
            yield s


def title_case(s):
    small = {"and", "or", "of", "the", "for", "to", "in", "on", "with", "a"}
    return " ".join(w.lower() if i and w.lower() in small else w.capitalize() for i, w in enumerate(s.lower().split()))


def main():
    sections, cur, intro = [], None, False
    for s in toc_lines():
        m = re.match(r"Section ([A-M]):\s*(.+)$", s)
        if m:
            cur = dict(letter=m.group(1), name=title_case(m.group(2)), topics=[])
            sections.append(cur)
        elif s == "Introduction":
            intro = True
        elif cur:
            cur["topics"].append(s)
    if len(sections) != 13 or not all(sec["topics"] for sec in sections[:-1]):
        raise SystemExit(f"Unexpected TOC parse: {[(x['letter'], len(x['topics'])) for x in sections]}")

    notice = ("This handbook is commercially copyrighted (“All rights reserved”; each page reads “Do not copy, "
              "print, share, or redistribute”). This hub lists its outline only. Use your own copy.")
    docs = [dict(
        id="pfc-handbook-2025", title="Prolonged Field Care Field Handbook (2025)",
        description=f"1st Edition · Breakaway Media, LLC · {len(sections)} sections, {sum(len(x['topics']) for x in sections)} topics",
        section="Prolonged Field Care Field Handbook", type="BOOK", refOnly=True, updated="2025", book=["pfc"],
        meta=[["Title", "Prolonged Field Care Field Handbook"], ["Edition", "1st Edition, Official 2025 Edition"],
              ["Publisher", "Breakaway Media, LLC"], ["ISBN", "979-8-9902257-4-9"],
              ["For use with", "Prolonged Field Care, Austere Emergency Care, and Prolonged Casualty Care education, training, and applications"]],
        details=[{"heading": "Sections", "items": [f"Section {x['letter']}: {x['name']}" for x in sections]}],
        noticeLabel="Copyrighted.", notice=notice, source=BOOK + ".",
        related=["cpg/cpg-91"], tags=["pfc", "pcc", "handbook", "prolonged field care", "austere"])]
    for x in sections:
        docs.append(dict(
            id=f"pfc-handbook-{x['letter'].lower()}", title=f"Section {x['letter']}: {x['name']}",
            description=f"PFC Field Handbook · {len(x['topics'])} topics" if x["topics"] else "PFC Field Handbook",
            section="Prolonged Field Care Field Handbook", type=f"SEC {x['letter']}", refOnly=True, book=["pfc"],
            meta=[["Handbook", "Prolonged Field Care Field Handbook (2025)"], ["Section", f"{x['letter']}: {x['name']}"]],
            details=[{"heading": "Topics in this section", "items": x["topics"]}] if x["topics"] else [],
            noticeLabel="Copyrighted.", notice=notice, source=BOOK + f", Section {x['letter']}.",
            tags=["pfc", "handbook", x["name"].lower()] + [w.lower() for t in x["topics"] for w in re.findall(r"[A-Za-z]{4,}", t)][:40]))
    OUT.write_text("/* GENERATED by scripts/build_fieldcare.py. Do not edit by hand; re-run the script instead. */\n"
                   "window.FIELDCARE_DOCUMENTS = " + json.dumps(docs, indent=1, ensure_ascii=False) + ";\n")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(sections)} sections")
    for x in sections:
        print(f"  {x['letter']} {x['name'][:34]:34} {len(x['topics'])} topics: {'; '.join(x['topics'][:3])[:80]}")


if __name__ == "__main__":
    main()


